"""Generate manuscript tables (CSV) from FINAL_RESULTS — no manual numbers."""
import os

import pandas as pd

ROOT = os.path.join(os.path.dirname(__file__), "..")
FR = os.path.join(ROOT, "FINAL_RESULTS")
ANA = os.path.join(ROOT, "analysis")
TBL = os.path.join(ROOT, "tables")
os.makedirs(TBL, exist_ok=True)

rd = lambda f: pd.read_csv(os.path.join(FR, f))
wt = lambda d, f: d.round(4).to_csv(os.path.join(TBL, f), index=False)

# T1: levels & capabilities (structural, mirrors docs/LEVELS.md)
pd.DataFrame([
    {"id": "L0", "kind": "level", "ink_over_KM": "none",
     "recovers": "curve only"},
    {"id": "L1", "kind": "level", "ink_over_KM": "risk-set ticks",
     "recovers": "coarse n(t)"},
    {"id": "L2", "kind": "level (core)", "ink_over_KM":
        "teeth + digit header + packet strip",
     "recovers": "exact event process (t,n,d,c) within capacity"},
    {"id": "Cap A", "kind": "capability", "ink_over_KM": "none",
     "recovers": "pseudo-IPD expansion of L2 decode"},
    {"id": "Cap B", "kind": "capability", "ink_over_KM": "none",
     "recovers": "multi-arm comparison"},
    {"id": "Cap C", "kind": "capability", "ink_over_KM": "none",
     "recovers": "reanalysis endpoints (median/RMST/log-rank/Cox)"},
]).to_csv(os.path.join(TBL, "TABLE_1_levels_capabilities.csv"),
          index=False)

# T2: visual complexity (generated by run_levels into analysis/)
cx = os.path.join(ANA, "complexity.csv")
if os.path.exists(cx):
    d = (pd.read_csv(cx).groupby("variant").mean(numeric_only=True)
           .round(4).reset_index())
    d.to_csv(os.path.join(FR, "visual_complexity.csv"), index=False)
    wt(d, "TABLE_6_visual_complexity.csv")

# T3/T4: decomposed encode/decode timing
t = rd("benchmark_timing.csv")
wt(t[["path", "family", "N", "t_encode"]].rename(
    columns={"t_encode": "t_encode_s"}), "TABLE_3_encode.csv")
wt(t[["path", "family", "N", "t_decode"]].rename(
    columns={"t_decode": "t_decode_s"}), "TABLE_4_decode.csv")

# T5: existing-method comparison (Guyot) — corrected exactness metrics
c = rd("existing_method_comparison.csv")
wt((c.groupby(["pipeline", "n"])
      .agg(exact_group_fraction=("exact_group_fraction", "mean"),
           exact_run=("exact_run", "mean"),
           km_linf=("km_linf", "mean"),
           d_err=("d_err", "mean"), t_total=("t_total", "mean"))
      .reset_index()), "TABLE_8_existing_methods.csv")

# T6: degradation grid — three metrics + Wilson CI + runtime
dg = rd("degradation.csv")
wt(dg[["dpi", "degradation", "n", "P_OK", "P_OK_lo", "P_OK_hi",
       "P_exact_given_OK", "P_exact", "P_exact_lo", "P_exact_hi",
       "d_err_med", "t_decode_med", "t_decode_p95"]],
   "TABLE_5_dpi_degradation.csv")

# T7: pseudo-IPD reanalysis (practical grid)
ra = rd("pseudo_ipd_validation.csv")
wt(ra.groupby("N").mean(numeric_only=True).reset_index(),
   "TABLE_7_reanalysis.csv")

# T8: capacity panels A-D = practical/stress x vector/raster
cap = rd("capacity_results.csv")
cap["panel"] = cap.family.map(
    {"practical": "practical", "stress": "STRESS TEST"}) \
    + "-" + cap.path.map({"svg": "vector", "raster": "raster"})
wt(cap[["panel", "stratum", "n", "acceptance", "cond_exact",
        "uncond_exact", "cap_util_med"]],
   "TABLE_2_capacity.csv")

# headline vector/raster summaries for the manuscript
for src, name in [("benchmark_vector.csv", "TABLE_9_vector_results.csv"),
                  ("benchmark_raster.csv", "TABLE_10_raster_results.csv")]:
    wt(rd(src), name)

print("tables written to", TBL)
